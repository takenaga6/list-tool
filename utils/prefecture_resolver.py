# ── 公開関数 ──────────────────────────────────────────────────────────────

def postal_code_to_prefecture(postal_code: str) -> Optional[str]:
    """郵便番号から都道府県を返す。不明な場合は None。"""
    digits = re.sub(r"[^\d]", "", postal_code)
    if len(digits) < 3:
        return None
    return ZIP_PREF.get(digits[:3])


def phone_to_prefecture(phone_number: str) -> Optional[str]:
    """市外局番から都道府県を返す。フリーダイヤル/IP電話/不明は None。"""
    digits = re.sub(r"[^\d]", "", phone_number)
    if len(digits) < 9:
        return None
    for skip in _SKIP_TEL_PREFIXES:
        if digits.startswith(skip):
            return None
    for length in (4, 3, 2):
        p = TEL_PREF.get(digits[:length])
        if p:
            return p
    return None


def _prefecture_from_text(text: str) -> str:
    """HP本文から都道府県を推定（最頻出・末尾優先のフォールバック）。"""
    if not text:
        return ""
    counts = {p: text.count(p) for p in ALL_PREFECTURES if p in text}
    if not counts:
        return ""
    max_count = max(counts.values())
    candidates = [p for p, c in counts.items() if c == max_count]
    if len(candidates) == 1:
        return candidates[0]
    # 同数の場合は最後に出現するものを優先（フッター = 本社住所の傾向）
    return max(candidates, key=lambda p: text.rfind(p))


def extract_prefecture_with_voting(
    postal_code: str,
    phone_number: str,
    hp_text: str,
    url: str = "",
) -> str:
    """
    郵便番号・電話番号・HP本文の3ソースで都道府県を判定。

    優先順位:
      1. 郵便番号と電話番号が一致 → その都道府県（最強）
      2. 郵便番号のみ有効          → 郵便番号を採用
      3. 電話番号のみ有効          → 電話番号を採用
      4. 両方なし                  → HP本文フォールバック（最頻出・末尾優先）

    郵便と電話が矛盾する場合: 郵便を優先し警告ログを出す。
    """
    zip_pref = postal_code_to_prefecture(postal_code)
    tel_pref = phone_to_prefecture(phone_number)

    if zip_pref and tel_pref and zip_pref != tel_pref:
        logger.warning(
            f"[ADDRESS_CONFLICT] zip={zip_pref}({postal_code}), "
            f"tel={tel_pref}({phone_number}), url={url}"
        )

    if zip_pref and tel_pref and zip_pref == tel_pref:
        return zip_pref
    if zip_pref:
        return zip_pref
    if tel_pref:
        return tel_pref
    return _prefecture_from_text(hp_text)
